#Exercício - ANTECESSOR E SUCESSOR

# Solicita o número ao usuário
n = int(input("Digite um número: "))

# Calcula antecessor e sucessor
antecessor = n - 1
sucessor = n + 1

# Exibe os resultados
print(f"O antecessor de {n} é {antecessor}")
print(f"O sucessor de {n} é {sucessor}")
